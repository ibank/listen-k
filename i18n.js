// Interpolates {name} placeholders. Missing keys or locales fall through in
// this order: requested locale → default locale → the raw key itself, so
// untranslated strings are never invisible.
function t(key, params, locale) {
  const useLocale = locale || currentLocale;
  const bundle = strings[useLocale] || strings[DEFAULT_LOCALE];
  let str = bundle[key];
  if (str == null) str = strings[DEFAULT_LOCALE][key];
  if (str == null) str = key;
  if (!params) return str;
  return str.replace(/\{(\w+)\}/g, (_, k) => (params[k] != null ? String(params[k]) : `{${k}}`));
}

let currentLocale = DEFAULT_LOCALE;
function setLocale(loc) {
  if (LOCALES.includes(loc)) currentLocale = loc;
  else currentLocale = DEFAULT_LOCALE;
}
function getLocale() { return currentLocale; }

// Best-effort system-locale → supported-locale mapper. Used on first launch
// before the user has explicitly picked a UI language.
function detectSystemLocale(sysLocale) {
  const s = String(sysLocale || '').toLowerCase();
  if (s.startsWith('ko')) return 'ko';
  if (s.startsWith('ja')) return 'ja';
  if (s.startsWith('zh')) return 'zh-CN';
  return 'en';
}

const LOCALE_LABELS = {
  ko: '한국어',
  en: 'English',
  ja: '日本語',
  'zh-CN': '简体中文',
};

const api = { LOCALES, DEFAULT_LOCALE, LOCALE_LABELS, strings, t, setLocale, getLocale, detectSystemLocale };
if (typeof module !== 'undefined' && module.exports) module.exports = api;
if (typeof window !== 'undefined') window.i18n = api;

